// Builds data/map.js from the Sengoku map project next door (../sengoku-map): province shapes, clans, dyes, crests and the
// 1467 map, plus which provinces border each other (computed here from the shapes) and the sea crossings (written by hand).
// Run: node tools/import.js   (re-run whenever the map project changes)
const fs = require('fs'), path = require('path'), vm = require('vm');
const SRC = path.join(__dirname, '..', '..', 'sengoku-map'), OUT = path.join(__dirname, '..');

const ctx = {};
vm.createContext(ctx);
// modern.js extends the era list past 1603; it needs places.js loaded first
for (const f of ['provinces', 'history', 'crests', 'places', 'modern']) vm.runInContext(fs.readFileSync(path.join(SRC, 'data', f + '.js'), 'utf8').replace(/^const (\w+)/gm, 'var $1'), ctx);
const { GEO, CLANS, DYES, BASE, CRESTS, ERAS, CHANGES, EVENTS, PHASES } = ctx;

// ---- borders: sample every outline, transformed, and call two provinces neighbours where their edges touch ----
function outline(s) {
  const [a, b, c, d, e, f] = s.m, T = (x, y) => [a * x + c * y + e, b * x + d * y + f];
  const nums = s.d.match(/[MLCz]|-?[\d.]+(?:e-?\d+)?/gi), pts = [];
  let i = 0, cmd = 'M', cur = [0, 0], start = [0, 0];
  const num = () => +nums[i++];
  const seg = (p, q) => { const n = Math.max(1, Math.ceil(Math.hypot(q[0] - p[0], q[1] - p[1]) / 1.2)); for (let k = 1; k <= n; k++) pts.push([p[0] + (q[0] - p[0]) * k / n, p[1] + (q[1] - p[1]) * k / n]); };
  while (i < nums.length) {
    if (/[MLCz]/i.test(nums[i])) cmd = nums[i++];
    if (cmd === 'z' || cmd === 'Z') { seg(cur, start); cur = start; continue; }
    if (cmd === 'M') { cur = start = T(num(), num()); pts.push(cur); cmd = 'L'; continue; }
    if (cmd === 'L') { const q = T(num(), num()); seg(cur, q); cur = q; continue; }
    if (cmd === 'C') { // sample the curve through its control points
      const c1 = T(num(), num()), c2 = T(num(), num()), q = T(num(), num()), p = cur;
      for (let k = 1; k <= 8; k++) { const t = k / 8, u = 1 - t; pts.push([0, 1].map(j => u * u * u * p[j] + 3 * u * u * t * c1[j] + 3 * u * t * t * c2[j] + t * t * t * q[j])); }
      cur = q; continue;
    }
    throw new Error('path command ' + cmd);
  }
  return pts;
}
const PIDS = Object.keys(GEO.provinces), EPS = 1.6, cell = new Map();
for (const p of PIDS) for (const s of GEO.provinces[p].shapes) for (const [x, y] of outline(s)) {
  const k = Math.floor(x / EPS) + ',' + Math.floor(y / EPS);
  if (!cell.has(k)) cell.set(k, []);
  cell.get(k).push([x, y, p]);
}
const adj = Object.fromEntries(PIDS.map(p => [p, new Set()]));
for (const [k, list] of cell) {
  const [cx, cy] = k.split(',').map(Number);
  for (let dx = -1; dx <= 1; dx++) for (let dy = -1; dy <= 1; dy++) {
    const other = cell.get((cx + dx) + ',' + (cy + dy));
    if (other) for (const [x, y, p] of list) for (const [u, v, q] of other) if (p !== q && Math.hypot(x - u, y - v) < EPS) { adj[p].add(q); adj[q].add(p); }
  }
}
// short sea crossings, the way armies actually went: straits, island hops, the bay mouths
const SEA = [['awaji', 'settsu'], ['awaji', 'harima'], ['awaji', 'awa_shikoku'], ['awaji', 'izumi'], ['sanuki', 'bizen'], ['iyo', 'aki'], ['iyo', 'suo'],
  ['iyo', 'bungo'], ['buzen', 'nagato'], ['chikuzen', 'nagato'], ['iki', 'hizen'], ['iki', 'chikuzen'], ['tsushima', 'iki'], ['sado', 'echigo'],
  ['oki', 'izumo'], ['oki', 'hoki'], ['awa_boso', 'sagami'], ['kii', 'awa_shikoku'], ['shima', 'mikawa'], ['awa_boso', 'musashi']];
const sea = new Set();
for (const [a, b] of SEA) {
  if (!adj[a] || !adj[b]) throw new Error('unknown province in SEA: ' + a + ' ' + b);
  if (!adj[a].has(b)) { adj[a].add(b); adj[b].add(a); sea.add([a, b].sort().join('|')); }
}

// ---- what the game needs from the map project ----
// the game shows no map: names are enough (the shapes stay in the map project)
const provinces = Object.fromEntries(PIDS.map(p => { const g = GEO.provinces[p]; return [p, { en: g.en, ja: g.ja }]; }));
const clans = Object.fromEntries(Object.entries(CLANS).filter(([, c]) => c.dye && DYES[c.dye]).map(([id, c]) => [id, { en: c.en, ja: c.ja, dye: c.dye, motif: c.motif, title: c.title || '', short: c.short || '' }]));
const crests = {};
fs.mkdirSync(path.join(OUT, 'crests'), { recursive: true });
for (const [id, c] of Object.entries(CRESTS)) {
  if (!clans[id]) continue;
  fs.copyFileSync(path.join(SRC, c.src), path.join(OUT, c.src));
  crests[id] = { src: c.src, invert: c.invert || false, file: c.file, page: c.page, licence: c.licence, artist: c.artist };
}
fs.mkdirSync(path.join(OUT, 'fonts'), { recursive: true });
for (const f of fs.readdirSync(path.join(SRC, 'fonts'))) if (/OFL\.txt$/.test(f)) fs.copyFileSync(path.join(SRC, 'fonts', f), path.join(OUT, 'fonts', f));

const json = x => JSON.stringify(x);
fs.writeFileSync(path.join(OUT, 'data', 'map.js'), `// Generated by tools/import.js from ../sengoku-map: don't edit by hand.
// Province shapes: ${GEO.source}. Clans, dyes, the map by year and the history: written for the Sengoku map project.
const GEO = ${json({ source: GEO.source, provinces })};
const ADJ = ${json(Object.fromEntries(PIDS.map(p => [p, [...adj[p]].sort()])))};
const SEA_LINKS = ${json([...sea])};
const DYES = ${json({ ...DYES, rikyu: '#8a907c' })};
const CLANS = ${json(clans)};
const BASE_1467 = ${json(BASE)};
// [year, province, holder (a clan, [two clans] for a split province, or null)], in year order, to 1945
const CHANGES = ${json(CHANGES.filter(c => provinces[c[1]]).map(c => c.slice(0, 3)).sort((a, b) => a[0] - b[0]))};
// the history, 1467-1945: the game's chapters
const EVENTS = ${json(EVENTS.map(e => ({ id: e.id, year: e.year, en: e.en, ja: e.ja, at: e.at, sides: (e.sides || []).filter(Boolean), winner: e.winner || null, short: e.short })).sort((a, b) => a.year - b.year))};
const PHASES = ${json(PHASES)};
const CRESTS = ${json(crests)};
const ERAS = ${json(ERAS)};
if (typeof module !== 'undefined') module.exports = { GEO, ADJ, SEA_LINKS, DYES, CLANS, BASE_1467, CHANGES, EVENTS, PHASES, CRESTS, ERAS };
`);
const lonely = PIDS.filter(p => !adj[p].size);
console.log('provinces', PIDS.length, 'borders', PIDS.reduce((s, p) => s + adj[p].size, 0) / 2, 'sea', sea.size, 'crests', Object.keys(crests).length, lonely.length ? 'NO NEIGHBOURS: ' + lonely : '');
