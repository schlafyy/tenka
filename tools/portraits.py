"""Fetches the guests' portraits: each guest's lead image on English Wikipedia, kept only when Wikimedia Commons lists it
as public domain or under a Creative Commons licence (the licence and author go into data/portraits.js for the credits).
Run: python tools/portraits.py [guest ids]   (needs the network; writes portraits/<id>.jpg and data/portraits.js;
with ids, fetches only those and keeps the rest)"""
import io, json, os, re, time, urllib.error, urllib.parse, urllib.request
from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
UA = {"User-Agent": "TenkaGame/1.0 (personal hobby project; portrait fetch)"}
WIKI = {  # guest id -> English Wikipedia article
    "juko": "Murata_Jukō", "jutei": "Kamiya_Jutei", "nobunaga": "Oda_Nobunaga", "rikyu": "Sen_no_Rikyū",
    "hideyoshi": "Toyotomi_Hideyoshi", "ieyasu": "Tokugawa_Ieyasu", "shinroku": "Yamanaka_Shinroku", "takatoshi": "Mitsui_Takatoshi",
    "koan": "Yodoya_Koan", "baigan": "Ishida_Baigan", "tadataka": "Inō_Tadataka", "hokusai": "Hokusai", "sontoku": "Ninomiya_Sontoku",
    "ryoma": "Sakamoto_Ryōma", "yataro": "Iwasaki_Yatarō", "eiichi": "Shibusawa_Eiichi", "masaru": "Inoue_Masaru",
    "yukichi": "Fukuzawa_Yukichi", "osuke": "Hibi_Ōsuke", "konosuke": "Kōnosuke_Matsushita", "soichiro": "Soichiro_Honda",
    "ibuka": "Masaru_Ibuka", "tezuka": "Osamu_Tezuka", "yamauchi": "Hiroshi_Yamauchi", "iwata": "Satoru_Iwata",
}
# chosen by hand where the English lead image is a statue or missing (period portraits found on Japanese Wikipedia)
FILES = {"shinroku": "Konoike_Shinroku.jpg", "tadataka": "Ino_Tadataka_(cropped).jpg", "sontoku": "Ninomiya-Sontoku.jpg",
         "masaru": "Inoue_Masaru.jpg", "osuke": "Ousuke_Hibi.jpg"}
OK = re.compile(r"^(public domain|pd|cc0|cc[- ]by)", re.I)

def get(url):
    # Wikimedia asks for a gentle pace: a pause before each request, and a longer one when told to slow down
    for wait in (1, 5, 15, 40):
        time.sleep(wait)
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=30) as r:
                return r.read()
        except urllib.error.HTTPError as e:
            if e.code != 429: raise
    raise RuntimeError("Wikimedia kept answering 429: " + url)

def api(host, **q):
    q.update(format="json", formatversion="2")
    return json.loads(get(f"https://{host}/w/api.php?" + urllib.parse.urlencode(q)))

def main(only=()):
    os.makedirs(os.path.join(ROOT, "portraits"), exist_ok=True)
    out = os.path.join(ROOT, "data", "portraits.js")
    found = {}
    if only:  # keep what is there
        s = open(out, encoding="utf8").read()
        found = json.loads(s[s.index("= ") + 2:s.index(";" + chr(10) + "if")])
    for gid, title in WIKI.items():
        if only and gid not in only: continue
        name = FILES.get(gid) or api("en.wikipedia.org", action="query", prop="pageimages", piprop="name", titles=title, redirects=1)["query"]["pages"][0].get("pageimage")
        if not name:
            print(gid, "no image"); continue
        info = api("commons.wikimedia.org", action="query", prop="imageinfo", iiprop="url|extmetadata", iiurlwidth=360, titles="File:" + name)["query"]["pages"][0]
        if "imageinfo" not in info:
            print(gid, "not on Commons:", name); continue
        ii = info["imageinfo"][0]; md = ii.get("extmetadata", {})
        lic = re.sub("<[^>]+>", "", md.get("LicenseShortName", {}).get("value", "")).strip()
        if not OK.match(lic):
            print(gid, "skipped, licence:", lic); continue
        author = re.sub("<[^>]+>", "", md.get("Artist", {}).get("value", "unknown")).strip()[:120]
        im = Image.open(io.BytesIO(get(ii["thumburl"]))).convert("RGB")
        im.thumbnail((240, 320))
        im.save(os.path.join(ROOT, "portraits", gid + ".jpg"), quality=82, optimize=True)
        found[gid] = {"src": f"portraits/{gid}.jpg", "file": name, "page": ii["descriptionurl"], "licence": lic, "author": author}
        print(gid, "ok", lic)
    found = {g: found[g] for g in WIKI if g in found}  # in the guests' order
    with open(out, "w", encoding="utf8") as f:
        f.write("// Generated by tools/portraits.py: the guests' portraits from Wikimedia Commons, with their licences. Don't edit by hand.\n")
        f.write("const PORTRAITS = " + json.dumps(found, ensure_ascii=False, indent=1) + ";\n")
        f.write("if (typeof module !== 'undefined') module.exports = { PORTRAITS };\n")
    print(len(found), "of", len(WIKI))

if __name__ == "__main__":
    import sys
    main(sys.argv[1:])
